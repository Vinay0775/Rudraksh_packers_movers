  function translateAdminDOM(lang) {
    const isDocAdmin = document.body && (
      document.body.classList.contains('cyber-dark-body') || 
      document.getElementById('cyberAdminLayout') ||
      document.getElementById('adminLoginOverlay')
    );
    if (!isDocAdmin) return;

    // Traverse all elements in admin layout, overlay, and any modals
    const targets = document.querySelectorAll(
      '#cyberAdminLayout *, #adminLoginOverlay *, .cyber-modal *, .modal *'
    );

    targets.forEach(el => {
      if (el.hasAttribute('data-i18n')) return;
      if (['SCRIPT', 'STYLE', 'INPUT', 'TEXTAREA', 'SELECT', 'SVG', 'PATH'].includes(el.tagName)) {
        // For inputs, translate placeholder if matching
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          const ph = el.getAttribute('placeholder');
          if (ph) {
            if (lang === 'hi') {
              if (!el.hasAttribute('data-orig-ph')) el.setAttribute('data-orig-ph', ph);
              const origPh = el.getAttribute('data-orig-ph').trim();
              if (adminDictionary[origPh]) {
                el.setAttribute('placeholder', adminDictionary[origPh]);
              }
            } else if (el.hasAttribute('data-orig-ph')) {
              el.setAttribute('placeholder', el.getAttribute('data-orig-ph'));
            }
          }
        }
        return;
      }

      // If element has direct text nodes
      const textNodes = Array.from(el.childNodes).filter(n => n.nodeType === 3 && n.nodeValue.trim().length > 0);
      if (textNodes.length === 0) return;

      // Extract the combined text of these direct text nodes
      const rawText = textNodes.map(n => n.nodeValue.trim()).join(' ');
      if (!rawText) return;

      if (lang === 'hi') {
        if (!el.hasAttribute('data-orig-en')) {
          el.setAttribute('data-orig-en', rawText);
        }
        const orig = el.getAttribute('data-orig-en').trim();
        if (adminDictionary[orig]) {
          textNodes[0].nodeValue = ' ' + adminDictionary[orig] + ' ';
          for (let i = 1; i < textNodes.length; i++) {
            textNodes[i].nodeValue = '';
          }
        }
      } else {
        if (el.hasAttribute('data-orig-en')) {
          const orig = el.getAttribute('data-orig-en');
          textNodes[0].nodeValue = ' ' + orig + ' ';
          for (let i = 1; i < textNodes.length; i++) {
            textNodes[i].nodeValue = '';
          }
        }
      }
    });
  }

  function toggleLanguage() {
    const current = getCurrentLanguage();
    const next = current === 'en' ? 'hi' : 'en';
    applyLanguage(next);
  }

  // Export to global scope
  window.i18n = {
    t: t,
    applyLanguage: applyLanguage,
    toggleLanguage: toggleLanguage,
    getCurrentLanguage: getCurrentLanguage,
    translateAdminDOM: translateAdminDOM,
    translations: translations,
    adminDictionary: adminDictionary
  };
  window.toggleLanguage = toggleLanguage;

  // Auto initialize on DOM load
  document.addEventListener('DOMContentLoaded', () => {
    const saved = getCurrentLanguage();
    if (saved === 'hi') {
      applyLanguage('hi');
    }
  });

  // Re-run admin translation whenever tab changes or dynamic data loads
  window.addEventListener('languageChanged', (e) => {
    translateAdminDOM(e.detail.lang);
  });

  // MutationObserver to translate dynamically rendered table rows in admin panel
  if (typeof MutationObserver !== 'undefined') {
    let debounceTimer;
    const observer = new MutationObserver(() => {
      const current = getCurrentLanguage();
      if (current === 'hi') {
        clearTimeout(debounceTimer);
        debounceTimer = setTimeout(() => {
          translateAdminDOM('hi');
        }, 50);
      }
    });

    document.addEventListener('DOMContentLoaded', () => {
      const mainContent = document.getElementById('cyberMainContent') || document.getElementById('cyberAdminLayout') || document.body;
      if (mainContent) {
        observer.observe(mainContent, { childList: true, subtree: true });
      }
    });
  }

